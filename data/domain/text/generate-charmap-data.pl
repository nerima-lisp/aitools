#!/usr/bin/env perl
# Regenerates data/domain/text/{cp932,euc-jp}-data*.lisp from glibc's
# localedata charmaps (share/i18n/charmaps/WINDOWS-31J.gz and EUC-JP.gz in
# the glibc output of nixpkgs; any glibc 2.42 build ships byte-identical
# tables). Usage, from the repository root:
#
#   gzip -dc <glibc>/share/i18n/charmaps/WINDOWS-31J.gz \
#     | perl data/domain/text/generate-charmap-data.pl cp932 'glibc 2.42 WINDOWS-31J' data/domain/text
#   gzip -dc <glibc>/share/i18n/charmaps/EUC-JP.gz \
#     | perl data/domain/text/generate-charmap-data.pl euc-jp 'glibc 2.42 EUC-JP' data/domain/text
#
# Each CHARMAP line "<Uxxxx> /xHH[/xHH...] NAME" becomes one triple
# (byte-code code-point reversible), byte-code being the byte sequence read
# as a big-endian integer. Lines glibc prefixes with %IRREVERSIBLE% decode
# but are never chosen when encoding (reversible 0).
use strict;
use warnings;
use File::Spec;

my ($name, $source, $output_directory) = @ARGV;
die "usage: generate-charmap-data.pl NAME SOURCE-LABEL OUTPUT-DIRECTORY < charmap\n"
  unless defined $output_directory;
die "invalid table name\n" unless $name =~ /\A[a-z0-9-]+\z/;
die "output directory does not exist: $output_directory\n"
  unless -d $output_directory;

my @triples;
my $in_map = 0;
while (my $line = <STDIN>) {
  if ($line =~ /^CHARMAP/) { $in_map = 1; next; }
  if ($line =~ /^END CHARMAP/) { last; }
  next unless $in_map;
  next unless $line =~ m{^(%IRREVERSIBLE%)?<U([0-9A-Fa-f]+)>\s+((?:/x[0-9a-fA-F]{2})+)\s};
  my ($irreversible, $unicode, $bytes) = ($1, hex($2), $3);
  my $code = 0;
  $code = $code * 256 + hex($1) while $bytes =~ m{/x([0-9a-fA-F]{2})}g;
  push @triples, [$code, $unicode, $irreversible ? 0 : 1];
}
die "no CHARMAP entries read\n" unless @triples;
@triples = sort { $a->[0] <=> $b->[0] || $b->[2] <=> $a->[2] } @triples;

my $triples_per_line = 12;
my $lines_per_part = 240;
my $triples_per_part = $triples_per_line * $lines_per_part;
my $part_count = int((@triples + $triples_per_part - 1) / $triples_per_part);
my $symbol = "*${name}-mapping*";
my @part_symbols;

for my $part_index (0 .. $part_count - 1) {
  my $part_number = $part_index + 1;
  my $part_symbol = sprintf("*%s-mapping-part-%03d*", $name, $part_number);
  my $part_filename = sprintf("%s-data-part-%03d.lisp", $name, $part_number);
  my $part_path = File::Spec->catfile($output_directory, $part_filename);
  my $start = $part_index * $triples_per_part;
  my $part_size = @triples - $start;
  $part_size = $triples_per_part if $part_size > $triples_per_part;

  open my $output, ">", $part_path or die "cannot write $part_path: $!\n";
  print {$output} ";;;;\n";
  print {$output} ";;;; GENERATED by data/domain/text/generate-charmap-data.pl from $source\n";
  print {$output} ";;;; Part $part_number/$part_count of the $name mapping.\n";
  print {$output} "(in-package #:aitools.data)\n\n";
  print {$output} "(defparameter $part_symbol\n  #(\n";
  for (my $offset = 0; $offset < $part_size; $offset += $triples_per_line) {
    my $end = $offset + $triples_per_line - 1;
    $end = $part_size - 1 if $end >= $part_size;
    print {$output} "    ";
    for my $local_index ($offset .. $end) {
      print {$output} " " if $local_index > $offset;
      print {$output} join(" ", @{$triples[$start + $local_index]});
    }
    print {$output} "\n";
  }
  print {$output} "  ))\n";
  close $output or die "cannot finish $part_path: $!\n";
  push @part_symbols, $part_symbol;
}

my $data_path = File::Spec->catfile($output_directory, "${name}-data.lisp");
open my $output, ">", $data_path or die "cannot write $data_path: $!\n";
print {$output} ";;;;\n";
print {$output} ";;;; GENERATED by data/domain/text/generate-charmap-data.pl from $source\n";
print {$output} ";;;; A flat vector of (byte-code code-point reversible) triples sorted by\n";
print {$output} ";;;; byte-code; REVERSIBLE 0 marks a decode-only mapping.\n";
print {$output} "(in-package #:aitools.data)\n\n";
print {$output} "(defparameter $symbol\n  (concatenate 'simple-vector\n";
print {$output} "    $_\n" for @part_symbols;
print {$output} "    ))\n\n(export '$symbol)\n";
close $output or die "cannot finish $data_path: $!\n";
